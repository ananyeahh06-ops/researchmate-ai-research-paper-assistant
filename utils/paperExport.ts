import { ResearchPaper } from '../types/paper';

export function calculateWordCount(paper: ResearchPaper): number {
  if (!paper) return 0;
  const sectionsToCount = [
    paper.title || '',
    paper.abstract || '',
    (paper.keywords || []).join(' '),
    paper.introduction || '',
    paper.literatureReview || '',
    paper.researchProblem || '',
    paper.researchObjectives || '',
    paper.researchMethodology || '',
    paper.expectedResults || '',
    paper.conclusion || '',
    paper.futureScope || '',
    (paper.references || []).map((r) => r.citation).join(' '),
  ];

  const fullText = sectionsToCount.join(' ');
  return fullText
    .trim()
    .split(/\s+/)
    .filter((word) => word.length > 0).length;
}

export function estimateReadingTimeMinutes(wordCount: number): number {
  return Math.max(1, Math.ceil(wordCount / 220));
}

export function formatPaperAsText(paper: ResearchPaper): string {
  const hr = '================================================================================';
  const subHr = '--------------------------------------------------------------------------------';

  const dateStr = new Date(paper.createdAt).toLocaleDateString(undefined, {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
  });

  const keywordsStr = (paper.keywords || []).join('; ');

  const referencesStr = (paper.references || [])
    .map((ref, idx) => {
      const num = `[${idx + 1}]`;
      let note = '';
      if (ref.verificationNote) {
        note = `\n     (Verification Note: ${ref.verificationNote})`;
      }
      return `${num} ${ref.citation}${note}`;
    })
    .join('\n\n');

  return `${hr}
RESEARCH PAPER DRAFT
Generated by ResearchMate – AI Research Paper Assistant
${hr}

TITLE:
${paper.title}

Academic Field:   ${paper.field}
Paper Type:       ${paper.paperType}
Citation Style:   ${paper.citationStyle}
Date Generated:   ${dateStr}

${hr}
ABSTRACT
${subHr}
${paper.abstract}

KEYWORDS:
${keywordsStr}

${hr}
1. INTRODUCTION
${subHr}
${paper.introduction}

${hr}
2. LITERATURE REVIEW
${subHr}
${paper.literatureReview}

${hr}
3. RESEARCH PROBLEM
${subHr}
${paper.researchProblem}

${hr}
4. RESEARCH OBJECTIVES
${subHr}
${paper.researchObjectives}

${hr}
5. RESEARCH METHODOLOGY
${subHr}
${paper.researchMethodology}

${hr}
6. EXPECTED RESULTS
${subHr}
${paper.expectedResults}

${hr}
7. CONCLUSION
${subHr}
${paper.conclusion}

${hr}
8. FUTURE SCOPE
${subHr}
${paper.futureScope}

${hr}
9. REFERENCES & SCHOLARLY FRAMEWORK
(VERIFICATION REQUIRED: AI-suggested references represent relevant literature
themes and key authors. Please verify exact publication years, volumes, and DOIs
against official academic indexes like CrossRef, PubMed, or Google Scholar prior to submission.)
${subHr}
${referencesStr}

${hr}
[End of Draft – Generated with ResearchMate]
`;
}

export function formatPaperAsMarkdown(paper: ResearchPaper): string {
  const keywordsStr = (paper.keywords || []).map((k) => `\`${k}\``).join(' • ');

  const referencesStr = (paper.references || [])
    .map((ref, idx) => {
      return `${idx + 1}. ${ref.citation}\n   - *Status: Verification Required (${ref.suggestedSourceType || 'Academic Source'})*\n   - [Search on Google Scholar](https://scholar.google.com/scholar?q=${encodeURIComponent(ref.doiQuery || ref.citation)})`;
    })
    .join('\n\n');

  return `# ${paper.title}

**Academic Field:** ${paper.field} | **Paper Type:** ${paper.paperType} | **Citation Style:** ${paper.citationStyle}  
*Draft generated via ResearchMate on ${new Date(paper.createdAt).toLocaleDateString()}*

---

## Abstract
${paper.abstract}

**Keywords:** ${keywordsStr}

---

## 1. Introduction
${paper.introduction}

---

## 2. Literature Review
${paper.literatureReview}

---

## 3. Research Problem
${paper.researchProblem}

---

## 4. Research Objectives
${paper.researchObjectives}

---

## 5. Research Methodology
${paper.researchMethodology}

---

## 6. Expected Results
${paper.expectedResults}

---

## 7. Conclusion
${paper.conclusion}

---

## 8. Future Scope
${paper.futureScope}

---

## 9. References
> **Important Academic Notice:** AI-suggested references must be verified for exact volume, issue, year, and author ordering in indexing databases (e.g., CrossRef, IEEE Xplore, PubMed, Scopus, Google Scholar).

${referencesStr}
`;
}

export function downloadTextFile(filename: string, content: string, mimeType = 'text/plain;charset=utf-8') {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = filename;
  document.body.appendChild(anchor);
  anchor.click();
  document.body.removeChild(anchor);
  URL.revokeObjectURL(url);
}

export function getScholarSearchUrl(query: string): string {
  return `https://scholar.google.com/scholar?q=${encodeURIComponent(query)}`;
}

export function getCrossrefSearchUrl(query: string): string {
  return `https://search.crossref.org/?q=${encodeURIComponent(query)}`;
}
